export type IndustryId = (typeof industries)[number]["id"]

export const industryIds = industries.map((industry) => industry.id) as [IndustryId, ...IndustryId[]]

const byId = new Map<string, Industry>(industries.map((industry) => [industry.id, industry]))

export function getIndustry(id: string): Industry {
  const industry = byId.get(id)
  if (!industry) throw new Error(`Unknown industry: ${id}`)
  return industry
}

/** Matches label, category, and aliases; used by the searchable selector. */
export function searchIndustries(query: string): Industry[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return [...industries]
  return industries.filter((industry) => {
    const category = industryCategories.find((entry) => entry.id === industry.category)?.label ?? ""
    return [industry.label, category, ...industry.aliases].some((text) => text.toLowerCase().includes(needle))
  })
}
