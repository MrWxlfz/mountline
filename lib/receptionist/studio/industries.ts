/*
 * Industry knowledge for Studio receptionists. Each entry is what a good front-desk person in that
 * line of work already knows: how callers describe what they want, what to ask (in what order), what
 * counts as urgent, and the lines not to cross. The prompt generator reads these; nothing here is a
 * template with the business name swapped in.
 *
 * "services" are typical for the industry. In demo mode the receptionist may treat them as offered;
 * in live mode only the business context decides what's offered.
 */

